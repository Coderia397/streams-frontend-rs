"""The icon fonts cut down to the icons the site uses (2026-10-23): Phosphor's three fonts (regular, bold, fill; about 140 KB each) and
their stylesheets (about 80 KB each, loaded before the first paint) became one stylesheet of a few KB and three small fonts.

    uv run --with fonttools --with brotli python3 scripts/subset_icons.py           # writes assets/phosphor/icons*.woff2 and icons.css
    python3 scripts/subset_icons.py --check                                          # fails when the code uses an icon the subset lacks

The icons in use are every `ph-<name>` in the source plus every string that is exactly an icon's name (icons passed by name, such as
icon="devices", which a component turns into `ph-{icon}`), in this app and in the engine (../streams-engine/src: the billboard's lines
name their icons there). The full fonts stay in assets/phosphor/<weight>/ as the source.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PH = ROOT / "assets" / "phosphor"
WEIGHTS = {"regular": ("Phosphor", "ph", "Phosphor.woff2"), "bold": ("Phosphor-Bold", "ph-bold", "Phosphor-Bold.woff2"), "fill": ("Phosphor-Fill", "ph-fill", "Phosphor-Fill.woff2")}
MODIFIERS = {"bold", "fill", "light", "thin", "duotone", "regular"}


def glyphs(weight):
    css = (PH / weight / "style.css").read_text(encoding="utf-8")
    cls = WEIGHTS[weight][1]
    return {m.group(1): m.group(2) for m in re.finditer(r"\." + re.escape(cls) + r"\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*\"\\([0-9a-f]+)\"", css)}


def used(names):
    found = set()
    sources = list((ROOT / "src").rglob("*.rs")) + list((ROOT.parent / "streams-engine" / "src").rglob("*.rs"))
    for f in sources:
        text = f.read_text(encoding="utf-8")
        found.update(n for n in re.findall(r"ph-([a-z0-9]+(?:-[a-z0-9]+)*)", text) if n not in MODIFIERS)
        found.update(s for s in re.findall(r'"([a-z0-9]+(?:-[a-z0-9]+)*)"', text) if s in names)
    return {n for n in found if n in names}


def base_rule(weight):
    css = (PH / weight / "style.css").read_text(encoding="utf-8")
    cls = WEIGHTS[weight][1]
    m = re.search(r"\n\." + re.escape(cls) + r" \{.*?\n\}", css, re.S)
    return m.group(0).strip()


def main():
    names = glyphs("regular")
    want = sorted(used(set(names)))
    out_css = PH / "icons.css"
    if "--check" in sys.argv:
        have = set(re.findall(r"\.ph-([a-z0-9-]+):before", out_css.read_text(encoding="utf-8"))) if out_css.exists() else set()
        missing = [n for n in want if n not in have]
        for n in missing:
            print(f"icon not in assets/phosphor/icons.css: {n}")
        print(f"{len(want)} icons used, {len(missing)} missing (run scripts/subset_icons.py)")
        sys.exit(1 if missing else 0)

    from fontTools import subset
    parts = ["/* Generated by scripts/subset_icons.py: Phosphor cut down to the icons the site uses. Do not edit. */"]
    for weight, (family, cls, font) in WEIGHTS.items():
        table = glyphs(weight)
        codes = sorted({int(table[n], 16) for n in want if n in table})
        target = PH / f"icons-{weight}.woff2"
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = ["*"]
        opts.notdef_outline = True
        f = subset.load_font(str(PH / weight / font), opts)
        s = subset.Subsetter(opts)
        s.populate(unicodes=codes)
        s.subset(f)
        subset.save_font(f, str(target), opts)
        parts.append(f'@font-face {{ font-family: "{family}"; src: url("./icons-{weight}.woff2") format("woff2"); font-weight: normal; font-style: normal; font-display: block; }}')
        parts.append(base_rule(weight))
        parts.extend(f'.{cls}.ph-{n}:before {{ content: "\\{table[n]}"; }}' for n in want if n in table)
        print(f"{weight}: {len(codes)} glyphs, {target.stat().st_size} bytes")
    out_css.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"icons.css: {out_css.stat().st_size} bytes, {len(want)} icons")


main()
