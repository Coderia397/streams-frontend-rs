"""Writes src/components/media/top_ten_numerals.rs: the Top 10 numerals 1 to 10 as SVG paths cut from the site's Inter (weight 700), so they
look the same in every browser and on every system and never wait for the web font. Each single digit is squeezed to the same advance
(0.6 of the box height, as the old textLength did), "10" to 1.08; the box leaves room for the outline, so nothing reaches past it.
  uv run --with fonttools --with brotli python scripts/make_top_ten_numerals.py fonts/inter/inter-latin-wght-normal.woff2 src/components/media/top_ten_numerals.rs"""
import sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
src, dst = sys.argv[1], sys.argv[2]
f = instantiateVariableFont(TTFont(src), {"wght": 700}, inplace=False)
gs = f.getGlyphSet(); cmap = f.getBestCmap()
TOP, BOTTOM = 1513, 23           # highest and lowest points of any digit (overshoot included), font units
MARGIN = 20                       # room for the outer half of the 34 unit outline
OLD_BOX = 2048 * 100 / 134        # the old 100 unit box at font size 134, in font units (the scale the old widths were set in)
fmt = lambda v: (f"{v:.1f}").rstrip("0").rstrip(".")
rows = []
for n in range(1, 11):
    digits = str(n)
    adv = sum(gs[cmap[ord(d)]].width for d in digits)
    target = (1.08 if n == 10 else 0.60) * OLD_BOX
    sx = target / adv
    pen = SVGPathPen(gs, ntos=fmt)
    x = 0.0
    for d in digits:
        g = gs[cmap[ord(d)]]
        g.draw(TransformPen(pen, (sx, 0, 0, -1, x * sx + MARGIN, TOP + MARGIN)))
        x += g.width
    width = adv * sx + 2 * MARGIN
    rows.append((f"{width:.1f}", pen.getCommands()))
height = TOP + BOTTOM + 2 * MARGIN
lines = ["//! Generated by scripts/make_top_ten_numerals.py from fonts/inter/inter-latin-wght-normal.woff2 (Inter, weight 700): the Top 10 numerals",
         "//! as SVG paths (note 113). Drawn as shapes, not text, so the numerals look the same in Safari, Chrome and Firefox on every system,",
         "//! never fall back to another font, and fit their box with the outline (the text numerals reached past the row on a Mac and were cut).",
         "",
         f"/// Height of every numeral's box (font units): the highest and lowest points of the digits plus room for the outline.",
         f"pub const BOX_HEIGHT: f32 = {height}.0;",
         "/// Width of the outline in the same units (drawn under the fill, so its outer half shows).",
         "pub const STROKE: f32 = 34.0;",
         "",
         "/// (box width, path) for 1 to 10.",
         "pub const NUMERALS: [(f32, &str); 10] = ["]
for w, d in rows:
    lines.append(f'    ({w}, "{d}"),')
lines.append("];")
open(dst, "w").write("\n".join(lines) + "\n")
print("height", height, "widths", [w for w, _ in rows], "bytes", sum(len(d) for _, d in rows))
